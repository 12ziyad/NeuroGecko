_UNKNOWN = ("11111", "10001", "10001", "10001", "10001", "10001", "11111")


def draw_text(frame: np.ndarray, text: str, x: int, y: int, scale: int = 2,
              colour=(255, 255, 255), shadow=(0, 0, 0)):
    """Draw `text` into `frame` in place. Shadowed, so it reads on any scene."""
    if shadow is not None:
        _blit(frame, text, x + scale, y + scale, scale, shadow)
    _blit(frame, text, x, y, scale, colour)
    return frame


def _blit(frame, text, x, y, scale, colour):
    h, w = frame.shape[:2]
    colour = np.asarray(colour, dtype=frame.dtype)
    cursor = x
    for char in text.upper():
        glyph = _GLYPHS.get(char, _UNKNOWN)
        for row, bits in enumerate(glyph):
            for col, bit in enumerate(bits):
                if bit != "1":
                    continue
                px, py = cursor + col * scale, y + row * scale
                if 0 <= px < w - scale and 0 <= py < h - scale:
                    frame[py:py + scale, px:px + scale] = colour
        cursor += 6 * scale
